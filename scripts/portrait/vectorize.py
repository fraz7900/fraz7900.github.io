"""
Turn the headshot into the layered vector portrait used on the home page.

    python scripts/portrait/vectorize.py public/images/fraz-ahmed.jpg src/content/portrait-vector.ts

Steps: cut the person out of the background (rembg, runs locally), lift detail in the face and
simplify the jacket, split the figure into six stacked tonal layers, and trace each layer to one
compound path (potracer, a pure-Python port of potrace). Writes a TypeScript module with the paths.

Dependencies (use a throwaway venv, they are not part of the site build):
    pip install "rembg[cpu]" potracer pillow numpy
The first run downloads rembg's u2net_human_seg model (about 170 MB) to ~/.u2net.
"""

import sys

import numpy as np
import potrace
from PIL import Image, ImageFilter
from rembg import new_session, remove

SIZE = 480
# Share of the face's tones below each cut. Six layers: the silhouette plus five lighter tones.
HEAD_QUANTILES = [0.16, 0.34, 0.52, 0.72, 0.9]
HEAD_BOTTOM = 0.62  # thresholds come from the head and shoulders, so the face gets the tonal range
SOFTEN_FROM, SOFTEN_RAMP = 0.5, 0.12  # below the chin, blend toward a blurred copy to calm the tweed
SPECKLE = 20  # potrace turdsize: drop specks smaller than this many pixels


def subject_mask(photo: Image.Image) -> np.ndarray:
    cutout = remove(photo, session=new_session("u2net_human_seg"))
    alpha = cutout.split()[-1].resize((SIZE, SIZE), Image.LANCZOS).filter(ImageFilter.GaussianBlur(1))
    return np.array(alpha) > 128


def luminance(photo: Image.Image) -> np.ndarray:
    grey = photo.convert("L").resize((SIZE, SIZE), Image.LANCZOS)
    detailed = grey.filter(ImageFilter.UnsharpMask(radius=4, percent=120, threshold=2))
    detailed = detailed.filter(ImageFilter.MedianFilter(3)).filter(ImageFilter.GaussianBlur(0.9))
    sharp = np.array(detailed, dtype=float)
    soft = np.array(detailed.filter(ImageFilter.GaussianBlur(4)), dtype=float)
    rows = np.linspace(0, 1, SIZE)[:, None]
    weight = np.clip((rows - SOFTEN_FROM) / SOFTEN_RAMP, 0, 1)
    return sharp * (1 - weight) + soft * weight


def fmt(value: float) -> str:
    return f"{value:.1f}".rstrip("0").rstrip(".")


def trace(layer: np.ndarray) -> str:
    """One compound path per layer; holes come out with opposite winding, so use fill-rule evenodd."""
    curves = potrace.Bitmap(~layer).trace(turdsize=SPECKLE, alphamax=1.1, opticurve=True, opttolerance=0.4)
    parts = []
    for curve in curves:
        start = curve.start_point
        path = [f"M{fmt(start.x)} {fmt(start.y)}"]
        for seg in curve.segments:
            end = seg.end_point
            if seg.is_corner:
                path.append(f"L{fmt(seg.c.x)} {fmt(seg.c.y)}L{fmt(end.x)} {fmt(end.y)}")
            else:
                path.append(f"C{fmt(seg.c1.x)} {fmt(seg.c1.y)} {fmt(seg.c2.x)} {fmt(seg.c2.y)} {fmt(end.x)} {fmt(end.y)}")
        parts.append("".join(path) + "Z")
    return "".join(parts)


def main(photo_path: str, out_path: str) -> None:
    photo = Image.open(photo_path).convert("RGB")
    mask = subject_mask(photo)
    lum = luminance(photo)
    head = mask.copy()
    head[int(SIZE * HEAD_BOTTOM) :, :] = False
    cuts = np.quantile(lum[head], HEAD_QUANTILES)
    layers = [mask] + [mask & (lum >= cut) for cut in cuts]
    paths = [trace(layer) for layer in layers]

    lines = [
        "// Generated by scripts/portrait/vectorize.py from public/images/fraz-ahmed.jpg. Do not edit by hand.",
        "",
        f"export const PORTRAIT_SIZE = {SIZE};",
        "",
        "/** Stacked tonal layers, darkest (the silhouette) first. Each is one compound path. */",
        "export const PORTRAIT_LAYERS: readonly string[] = [",
        *[f'  "{d}",' for d in paths],
        "];",
        "",
    ]
    with open(out_path, "w", encoding="utf-8") as out:
        out.write("\n".join(lines))
    print(f"{out_path}: {len(paths)} layers, {sum(map(len, paths)) // 1024} KB of path data")


if __name__ == "__main__":
    if len(sys.argv) != 3:
        sys.exit(__doc__)
    main(sys.argv[1], sys.argv[2])
